--Вывести все заказы, добавив колонку с рангом заказа внутри каждого клиента (на основе суммы заказа)

SELECT
    o.order_id,
    o.customer_id,
    c.name AS customer_name,
    o.total_amount,
    RANK() OVER (PARTITION BY o.customer_id ORDER BY o.total_amount DESC) AS order_rank --разбивает заказы по каждому клиенту отдельно
FROM Заказы o                                                                           --сортирует заказы по убыванию суммы внутри каждого клиента.
JOIN Клиенты c ON o.customer_id = c.customer_id                                         --Если у клиента два заказа с одинаковой суммой, они получат одинаковый ранг, а следующий пропустит номер
ORDER BY o.customer_id, order_rank;--Сортируем сначала по клиенту, чтобы сгруппировать заказы каждого клиента, затем сортируем по order_rank, чтобы отобразить заказы в порядке убывания суммы.
